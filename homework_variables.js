// Task 11 — Финальный микс (== vs ===, !!, type coercion)
// ============================================================
/*
   Предскажи результаты.
   Запиши ответ в комментарии ДО запуска, затем проверь.

   Ожидаемый результат:
   // строка 1: true (т.к. оператор == выполняет неявное приведение типов, "10" преобразуется в число 10, и 10 > 5)
   // строка 2: true (т.к. унарный + преобразует строку "10" в число 10, и 10 > 5)
   // строка 3: true (т.к. оператор == выполняет неявное приведение типов, "10" преобразуется в число 10, и 10 == 10)
   // строка 4: false (т.к. оператор === не выполняет приведение типов, строго сравнивает строку "10" и число 10, которые не равны)
   // строка 5: false (т.к. !!0 -> !true -> false)
   // строка 6: true (т.к. !!1 -> !false -> true)
   // строка 7: false (т.к. !!"" -> !true -> false)
   // строка 8: true (т.к. !!"hello" -> !false -> true)
   // строка 9: true (т.к. == вып. неявное приведение типов и null с undefined считаются равными)
   // строка 10: false (т.к. === не выполняет приведение типов и сравнивает null и undefined как разные типы)

   — Объясни разницу между == и === на примере строк 3 и 4
   // оператор == выполняет неявное приведение типов, поэтому "10" преобразуется в число 10, и сравнение "10" == 10 возвращает true (нестрогое сравнение).
   // оператор === не выполняет приведение типов, он сравнивает как есть, поэтому "10" === 10 возвращает false, т.к. это разные типы (строка и число) (здесь строгое сравнение).

   — Объясни что делает !! и зачем его используют
   // !! - это двойное логическое отрицание. Первый ! преобр. значение в boolean и инвертирует его, а второй ! снова инвертирует результат, возвр. значение в виде boolean.
   // его используют для быстрого преобразования любого значения в boolean, например, для проверки truthy/falsy значений.

   — Объясни почему null == undefined, но null !== undefined
   // null == undefined возвращает true, потому что оператор == выполняет неявное приведение типов и считает null и undefined равными (они оба считаются falsy значениями).
   // null !== undefined возвращает true, потому что оператор !== не выполняет приведение типов и сравнивает null и undefined как разные типы 
   // (null - это reference type (объект (js bug)), а undefined - это primitive type).
*/


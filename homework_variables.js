// Группа 1 — цепочки || (возвращает первое truthy значение)
/*
   Ожидаемый результат:
   // строка 1: finally! (т.к. первое truthу)
   // строка 2: false (последнее falsy)
   // строка 3: null (последнее falsy)
   // строка 4: last resort (первое truthу)
   
*/
console.log(0 || "" || null || "finally!");
console.log(null || 0 || undefined || false);
console.log("" || 0 || false || null);
console.log(null || false || "" || 0 || "last resort");

// Группа 2 — цепочки && (возвращает первое falsy значение)
/*
   Ожидаемый результат:
   // строка 1: 42 (т.к. все truthy, возвращает последнее truthу)
   // строка 2: 0 (первое falsy, дальше не проверяется)
   // строка 3: null (первое falsy)
*/
console.log(1 && "ok" && true && 42);
console.log(1 && 0 && "never" && true);
console.log("hello" && 42 && null && "world");

// Группа 3 — ! внутри выражения
/*
   Ожидаемый результат:
   // строка 1: true (все falsy, инвертированы ! в truthy)
   // строка 2: true (все falsy, инвертируются в truthy)
   // строка 3: true (возвращает true, если хотя бы одно истинно)
   // строка 4: false (первый !1 = false, дальше не проверяется)
*/
console.log(!"" && !null && !0);
console.log(!null && !undefined && !"");
console.log(!0 || !"hello");
console.log(!1 && !"");

// Группа 4 — && и || вместе
/*
   Ожидаемый результат:
   // строка 1: "world" (сначала вып. && -> возвр. 0, затем 0 || "world" -> "world" (т.к. 0 falsy, возвращается "world"))
   // строка 2: false (сначала вып. && -> возвр. false, затем null || false -> false)
   // строка 3: 42 (сначала вып. && -> возвр. посл. truthy 42, затем 0 || null || 42 -> 42 (т.к. 0 и null falsy, возвр. единственное truthy 42))
   // строка 4: "c" (сначала вып. "" && "a"-> возвр. false ""; затем "b" && "c" -> возвр. посл. truthy "c"; затем ""|| null || "b" -> возвр. единственное truthy "c")

   — Объясни в комментарии: почему && выполняется раньше ||?
   // т.к. по приоритету лог. операторы выполняются так: not -> and -> or. 
   // поэтому в выражениях ниже сначала вып. &&, потом ||.
*/
console.log("hello" && 0 || "world");
console.log(null || "ok" && false);
console.log(0 || null || "yes" && 42);
console.log("" && "a" || null || "b" && "c");

// Группа 5 — &&, || и ! все вместе
/*
   Ожидаемый результат:
   // строка 1: "fallback" (сначала вып. в скобках || -> возвр. "fallback", затем !null (true) && "fallback" -> "fallback", т.к. посл. truthy)
   // строка 2: "result"
   // строка 3: true
   // строка 4: "default"
   // строка 5: "done"
   // строка 6: "last"

   — Объясни: выражения всегда возвращают boolean или нет?
   // нет, не всегда, в зависимости от операторов - операторы сравнения всегда возвр. boolean, 
   // а лог. операторы могут возвращать любое значение в зависимости от того, что они обрабатывают (любое первое falsy значение для &&, первое truthy для ||).
*/
console.log(!null && ("" || "fallback"));
console.log(!0 && (null || "result"));
console.log(!"" && !0 || null);
console.log(!false && (0 || "") || "default");

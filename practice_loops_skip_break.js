// Task A — обратный отсчёт ракеты
// ============================================================
/*
   Сделай обратный отсчёт от 10 до 1 (число уменьшается).
   — на числе 4 ничего не выводи (пропусти шаг) — это "техническая пауза"
   — если число чётное, выведи "<число>... готовимся"
   — если нечётное, выведи просто число
   — после цикла выведи "Пуск!"
*/

for (let counter = 10; counter > 0; counter--) {
      if (counter === 4) 
         continue;
      if (counter % 2 === 0) {
         console.log(`${counter}... готовимся`);
      } else {
         console.log(counter);
      }
}

console.log("Пуск!");


// ============================================================
// Task B — накопление баллов
// ============================================================
/*
   Перебери числа от 1 до 30:
   — числа кратные 4 пропускай (не учитывай их)
   — остальные числа прибавляй к balance
   — как только balance станет больше 80 — выведи "Достаточно!" и останови цикл
   — после цикла выведи накопленный balance
*/

let balance = 0;

for (let a = 1; a <= 30; a++) {
   if (a % 4 ===0)
      continue;
   else {
      balance = balance + a;
   }
   if (balance > 80) {
      console.log("Достаточно!");
      break;
   }
}
console.log(`Баланс: ${balance}`);

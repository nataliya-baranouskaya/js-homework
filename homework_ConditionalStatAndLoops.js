// Task 14 — финальный микс
// ============================================================
/*
   Перебери числа от 1 до 50:
   — пропускай числа кратные 7
   — для чисел кратных 3 и 5 выведи "FizzBuzz"
   — для чисел кратных только 3 выведи "Fizz"
   — для чисел кратных только 5 выведи "Buzz"
   — иначе выведи само число
   — остановись на числе 40
*/

let num=1;
while (num<=50) {
    if (num>40) {
        break;
    }
    if (num % 7 === 0) {
        num++;
        continue;
    }
    if (num % 3 === 0 && num % 5 === 0) {
        console.log("FizzBuzz");
    } else if (num % 3 === 0) {
        console.log("Fizz");
    } else if (num % 5 === 0) {
        console.log("Buzz");
    } else {
        console.log(num);
    }
    num++;
}
